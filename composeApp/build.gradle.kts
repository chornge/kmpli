import org.jetbrains.kotlin.konan.target.KonanTarget

val host = org.jetbrains.kotlin.konan.target.HostManager.host

plugins {
    alias(libs.plugins.kotlin.multiplatform)
}

// `appVersion` in gradle/libs.versions.toml is the single declared version of the CLI.
// It is generated into Version.kt so `kmpli --version` reports it, and the
// verify-version job in .github/workflows/release.yml refuses to publish a tag
// that disagrees with it. Keep those three in sync; nothing else holds a version.
val generateVersionFile by tasks.registering {
    group = "build"
    description = "Generate Version.kt from the appVersion entry in the version catalog"

    val appVersion = libs.versions.appVersion.get()
    val outputDir = layout.buildDirectory.dir("generated/version/kotlin")

    inputs.property("appVersion", appVersion)
    outputs.dir(outputDir)

    doLast {
        outputDir.get().file("io/chornge/kmpli/Version.kt").asFile.apply {
            parentFile.mkdirs()
            writeText(
                """
                // Generated by the generateVersionFile Gradle task. Do not edit.
                package io.chornge.kmpli

                internal const val KMPLI_VERSION: String = "$appVersion"
                """.trimIndent() + "\n"
            )
        }
    }
}

kotlin {
    when (host) {
        KonanTarget.MACOS_X64 -> macosX64("macosX64") {
            binaries.executable {
                entryPoint = "io.chornge.kmpli.main"
                baseName = "kmpli"
            }
        }

        KonanTarget.MACOS_ARM64 -> macosArm64("macosArm64") {
            binaries.executable {
                entryPoint = "io.chornge.kmpli.main"
                baseName = "kmpli"
            }
        }

        // linux_arm64 has no Kotlin/Native host compiler of its own, so the aarch64 binary is
        // cross-compiled from the linux_x64 host. Kotlin downloads the aarch64 gcc toolchain and
        // sysroot automatically, but that sysroot carries no libcurl, so the CI job installs the
        // arm64 libcurl packages and the linker is pointed at them below.
        KonanTarget.LINUX_X64 -> {
            linuxX64("linuxX64") {
                binaries.executable {
                    entryPoint = "io.chornge.kmpli.main"
                    baseName = "kmpli"
                }
            }

            linuxArm64("linuxArm64") {
                binaries.executable {
                    entryPoint = "io.chornge.kmpli.main"
                    baseName = "kmpli"
                    // Where dpkg multiarch places arm64 libraries. Harmless when absent.
                    linkerOpts("-L/usr/lib/aarch64-linux-gnu")
                }
            }
        }

        KonanTarget.LINUX_ARM64 -> linuxArm64("linuxArm64") {
            binaries.executable {
                entryPoint = "io.chornge.kmpli.main"
                baseName = "kmpli"
            }
        }

        KonanTarget.MINGW_X64 -> mingwX64("mingwX64") {
            binaries.executable {
                entryPoint = "io.chornge.kmpli.main"
                baseName = "kmpli"
            }
        }

        else -> throw GradleException("Unsupported host: $host")
    }

    sourceSets {
        val commonMain by getting {
            kotlin.srcDir(generateVersionFile)
            dependencies {
                implementation(libs.ktor.client.core)
                implementation(libs.kotlinx.coroutines.core)
                implementation(libs.kotlinx.serialization.json)
            }
        }

        val commonTest by getting {
            dependencies {
                implementation(libs.kotlin.test)
            }
        }

        val nativeMain by creating {
            dependsOn(commonMain)
            dependencies {
                implementation(libs.ktor.client.curl)
                implementation(libs.squareup.okio)
                implementation(libs.mordant)
            }
        }

        // Tests for code that lives in nativeMain (e.g. TuiWizard). Wired to the host
        // target's test source set below, alongside nativeMain.
        val nativeTest by creating {
            dependsOn(commonTest)
        }

        when (host) {
            KonanTarget.MACOS_X64 -> {
                sourceSets.getByName("macosX64Main").dependsOn(nativeMain)
                sourceSets.getByName("macosX64Test").dependsOn(nativeTest)
            }

            KonanTarget.MACOS_ARM64 -> {
                sourceSets.getByName("macosArm64Main").dependsOn(nativeMain)
                sourceSets.getByName("macosArm64Test").dependsOn(nativeTest)
            }

            KonanTarget.LINUX_X64 -> {
                sourceSets.getByName("linuxX64Main").dependsOn(nativeMain)
                sourceSets.getByName("linuxX64Test").dependsOn(nativeTest)
                // linuxArm64 gets main sources only. Its tests are deliberately not wired:
                // the aarch64 test binary cannot execute on the x86_64 build host.
                sourceSets.getByName("linuxArm64Main").dependsOn(nativeMain)
            }

            KonanTarget.LINUX_ARM64 -> {
                sourceSets.getByName("linuxArm64Main").dependsOn(nativeMain)
                sourceSets.getByName("linuxArm64Test").dependsOn(nativeTest)
            }

            KonanTarget.MINGW_X64 -> {
                sourceSets.getByName("mingwX64Main").dependsOn(nativeMain)
                sourceSets.getByName("mingwX64Test").dependsOn(nativeTest)
            }

            else -> {} // Unsupported host
        }
    }
}

// The aarch64 test binary cannot run on the x86_64 build host, so keep it out of `allTests`.
// Without this, `./gradlew allTests` would try to execute it and fail.
tasks.matching { it.name == "linuxArm64Test" }.configureEach { enabled = false }

val nativeTargets = listOf(
    "MacosX64",
    "MacosArm64",
    "LinuxX64",
    "LinuxArm64",
    "MingwX64"
)

tasks.register<Copy>("copyBinariesToDist") {
    group = "distribution"
    description = "Copy native binaries to build/dist"

    nativeTargets.forEach { target ->
        val binaryDir = layout.buildDirectory.dir("bin/$target/releaseExecutable")
        from(binaryDir) {
            include("*")
            rename { fileName ->
                if (target.lowercase().startsWith("mingw")) fileName else fileName.removeSuffix(".kexe")
            }
        }
        into(layout.buildDirectory.dir("dist/$target"))
    }
}
